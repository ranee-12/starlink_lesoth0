        /*
         * Stores the selected checkout URL
         */

        let selectedCheckoutUrl = "";



        /*
         * OPEN POPUP
         */

        function openPlanModal(plan, price, checkoutUrl) {


            const details = planDetails[plan];


            if (!details) {

                alert("Plan information could not be found.");

                return;

            }


            /*
             * Save checkout URL
             */

            selectedCheckoutUrl = checkoutUrl;



            /*
             * Display selected plan
             */

            document.getElementById("modalPlanName").textContent =
                details.name;


            document.getElementById("modalPlanDuration").textContent =
                details.duration;


            document.getElementById("modalDescription").textContent =
                details.description;


            document.getElementById("modalPrice").textContent =
                "LSL " + price;


            document.getElementById("modalValidity").textContent =
                details.validity;



            /*
             * Display bullet points
             */

            const featureList =
                document.getElementById("modalFeatures");


            featureList.innerHTML = "";


            details.features.forEach(function(feature) {


                const li =
                    document.createElement("li");


                li.textContent = feature;


                featureList.appendChild(li);

            });



            /*
             * Show popup
             */

            document
                .getElementById("planModal")
                .classList.add("active");


            /*
             * Prevent background scrolling
             */

            document.body.style.overflow = "hidden";

        }



        /*
         * CLOSE POPUP
         */

        function closePlanModal() {


            document
                .getElementById("planModal")
                .classList.remove("active");


            document.body.style.overflow = "";

        }



        /*
         * PAY WITH ECOCASH
         *
         * Send customer to checkout.php
         */

        function proceedToEcoCash() {


            if (selectedCheckoutUrl !== "") {

                window.location.href =
                    selectedCheckoutUrl;

            }

        }



        /*
         * HANDLE VIEW DETAILS BUTTONS
         */

        document.addEventListener(
            "DOMContentLoaded",
            function() {


                const buttons =
                    document.querySelectorAll(".plan-button");


                buttons.forEach(function(button) {


                    button.addEventListener(
                        "click",
                        function(event) {


                            /*
                             * Stop the normal link
                             */

                            event.preventDefault();



                            /*
                             * Read the URL
                             */

                            const url =
                                new URL(
                                    button.href,
                                    window.location.origin
                                );



                            /*
                             * Get selected plan
                             */

                            const plan =
                                url.searchParams.get("plan");



                            /*
                             * Get price
                             */

                            const price =
                                url.searchParams.get("price");



                            /*
                             * Open popup
                             */

                            openPlanModal(
                                plan,
                                price,
                                button.href
                            );

                        }
                    );

                });

            }
        );



        /*
         * CLOSE WITH ESC KEY
         */

        document.addEventListener(
            "keydown",
            function(event) {


                if (event.key === "Escape") {

                    closePlanModal();

                }

            }
        );


